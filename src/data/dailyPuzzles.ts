function daysBetweenUtcDates(startDate: string, endDate: string): number {
  const start = Date.parse(`${startDate}T00:00:00Z`);
  const end = Date.parse(`${endDate}T00:00:00Z`);
  return Math.floor((end - start) / 86_400_000);
}

/**
 * Deterministic fallback puzzle for a UTC date (YYYY-MM-DD), used when
 * Supabase is not configured (local dev / tests).
 */
export function getFallbackDailyPuzzle(
  utcDate: string,
  includeParSolution = false,
): DailyPuzzle {
  const dayOffset = Math.max(0, daysBetweenUtcDates(DAILY_EPOCH_UTC, utcDate));
  const seed = DAILY_PUZZLE_SEEDS[dayOffset % DAILY_PUZZLE_SEEDS.length];

  return {
    id: `local-daily-${utcDate}`,
    puzzle_number: dayOffset + 1,
    puzzle_date: utcDate,
    title: seed.title,
    description: seed.description,
    difficulty: seed.difficulty,
    language: seed.language,
    start_text: seed.startText,
    target_text: seed.targetText,
    start_cursor_line: seed.startCursorLine ?? 0,
    start_cursor_ch: seed.startCursorCh ?? 0,
    par: seed.parSolution.length,
    min_keystrokes: seed.minKeystrokes,
    par_solution: includeParSolution ? seed.parSolution : null,
  };
}
